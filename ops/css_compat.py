"""Physical fallbacks for the CSS logical properties in static/css/app.css → static/css/compat.css.

Older phone browsers (Chrome/WebView before 87, some MIUI and Samsung browsers) ignore ``inset-inline-start``,
``padding-inline-start``, ``text-align:start``… so icons sat on top of the text and fields lost their padding.
Each rule that uses one of them gets a copy for ``html[dir=rtl]`` (start = right) and ``html[dir=ltr]``
(start = left); newer browsers map both to the same side, so nothing changes there.

Run after editing app.css:  python ops/css_compat.py
"""
import os
import re

import tinycss2

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, 'static', 'css', 'app.css')
OUT = os.path.join(HERE, 'static', 'css', 'compat.css')

SIDE = {'rtl': {'start': 'right', 'end': 'left'}, 'ltr': {'start': 'left', 'end': 'right'}}


def physical(name, value, d):
    s = SIDE[d]
    m = re.fullmatch(r'(inset|padding|margin|border)-inline-(start|end)(-[a-z]+)?', name)
    if m:
        base, side, rest = m.group(1), m.group(2), m.group(3) or ''
        prop = s[side] if base == 'inset' else f'{base}-{s[side]}{rest}'
        return [(prop, value)]
    if name == 'inset':
        v = value.split()
        v = (v * 4)[:4] if len(v) == 1 else (v + v)[:4] if len(v) == 2 else v + [v[1]] if len(v) == 3 else v
        return [('top', v[0]), ('right', v[1]), ('bottom', v[2]), ('left', v[3])]
    if name == 'inset-block':
        parts = value.split()
        return [('top', parts[0]), ('bottom', parts[-1])]
    if name in ('padding-inline', 'margin-inline'):
        parts = value.split()
        base = name.split('-')[0]
        return [(f'{base}-{s["start"]}', parts[0]), (f'{base}-{s["end"]}', parts[-1])]
    if name == 'text-align' and value.strip() in ('start', 'end'):
        return [('text-align', s[value.strip()])]
    return []


def rules(nodes, out, indent=''):
    for node in nodes:
        if node.type == 'qualified-rule':
            decls = tinycss2.parse_declaration_list(node.content, skip_whitespace=True, skip_comments=True)
            sel = tinycss2.serialize(node.prelude).strip()
            for d in ('rtl', 'ltr'):
                props = []
                for decl in decls:
                    if decl.type != 'declaration':
                        continue
                    val = tinycss2.serialize(decl.value).strip()
                    imp = '!important' if decl.important else ''
                    props += [f'{p}:{v}{imp}' for p, v in physical(decl.lower_name, val, d)]
                if props:
                    sels = ','.join(f'html[dir={d}] {x.strip()}' for x in sel.split(','))
                    out.append(f'{indent}{sels}{{{";".join(props)}}}')
        elif node.type == 'at-rule' and node.lower_at_keyword == 'media' and node.content:
            inner = []
            rules(tinycss2.parse_rule_list(node.content, skip_whitespace=True, skip_comments=True), inner, '  ')
            if inner:
                out.append(f'@media {tinycss2.serialize(node.prelude).strip()}{{')
                out.extend(inner)
                out.append('}')


def main():
    with open(SRC, encoding='utf-8') as f:
        sheet = tinycss2.parse_stylesheet(f.read(), skip_whitespace=True, skip_comments=True)
    out = ['/* generated by ops/css_compat.py from app.css — do not edit by hand */']
    rules(sheet, out)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{OUT}: {len(out) - 1} lines')


if __name__ == '__main__':
    main()
